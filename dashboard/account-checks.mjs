import assert from 'node:assert/strict';
import {accountValues,accountPanel} from './dist/account-panel.js';
import {accountPath} from './dist/terminal-api.js';
const data={paper:{available:true,initial_capital_rs:500000,marked_equity_rs:499000,net_closed_pnl_rs:-800,closed_trades:2,orders:[{},{}],position:{mark:{net_pnl_rs:-200}},trades:[],decisions:[]}};
assert.equal(accountValues(data).total,-1000);
assert.equal(accountValues(data).closed,-800);
assert.equal(accountValues(data).open,-200);
assert.equal(accountValues({paper:{available:false}}).total,null);
const html=accountPanel(data,'cloud','baseline',true);
assert.ok(html.includes('−₹1,000.00')&&html.includes('−₹800.00')&&html.includes('−₹200.00'));
assert.ok(html.includes('Original · 2% risk')&&html.includes('Experiment · 25% risk'));
assert.ok(accountPanel(data,'snapshot','adaptive25').includes('These loaded records belong to the original account'));
assert.equal(accountPath('/api/automation/start','adaptive25'),'/api/experiment/start');
assert.equal(accountPath('/api/automation/pause','adaptive25'),'/api/experiment/pause');
assert.equal(accountPath('/api/dashboard','adaptive25'),'/api/experiment/dashboard');
assert.equal(accountPath('/api/dashboard','baseline'),'/api/dashboard');
assert.equal(accountPath('/api/dashboard','arbitrary'),'/api/dashboard');
assert.equal(accountPath('/api/backtest/run','adaptive25'),'/api/backtest/run');
const unsafe=accountPanel({...data,intraday:{lot_sizing:{strategy:'<script>x</script>',as_of:'<img>',binding_limit:'<b>',risk_limited_lots:1,selected_lots:1}}},'cloud');
assert.ok(!unsafe.includes('<script>')&&!unsafe.includes('<img>'));
console.log('Account checks passed signed net P&L, missing data, profile isolation, action routing and sizing-label escaping.');
